import logging
from decimal import ROUND_HALF_EVEN, Decimal

import numpy as np
import pandas as pd
from django.db.models import F
from django.db.models.query import QuerySet

from publicatie_tabellen.constants_settings import (
    MEASURE_BEVTOTAAL,
    MEASURE_WVOORRBAG,
    SPATIAL_DIMENSION_GGW,
    SPATIAL_DIMENSION_WIJK,
    TEMPORAL_DIMENSIONTYPE_PEILDATUM,
)

logger = logging.getLogger(__name__)


def round_to_base(x, base=5):
    """round up / down to base"""
    return base * round(x / base)


def round_to_decimal(x, decimal):
    """
    banker's rounding: when a number is exactly halfway between two possible rounding amounts,
    it is rounded to the nearest even number. Use of package decimal because python round() doesn't
    give secure rounding half to even due to uncertainty with floats
    """

    number = Decimal(str(x))
    dec_str = "1" if decimal == 0 else "0." + "0" * (decimal - 1) + "1"
    rounded_number = number.quantize(Decimal(dec_str), rounding=ROUND_HALF_EVEN)

    return float(rounded_number)


def convert_queryset_into_dataframe(queryset: QuerySet) -> pd.DataFrame:
    """converts a queryset into a dataframe"""
    return pd.DataFrame(list(queryset.values()), columns=queryset._fields)


def copy_queryset(queryset: QuerySet, copy_to_model):
    """copy queryset into the copy_to_model"""
    new_item_list = []

    for item_obj in queryset:
        new_item_list.append(item_obj)

    copy_to_model.objects.bulk_create(new_item_list)


def copy_dataframe(dataframe: pd.DataFrame, copy_to_model):
    """copy dataframe into the copy_to_model
    df.columns must be equal to copy_to_model._fields"""
    fields = [i.name for i in copy_to_model._meta.get_fields()]
    fields.remove("id")  # autogenerated by model

    new_item_list = []

    for _, row in dataframe.iterrows():
        params = {}
        for f in fields:
            params[f] = row[f]
        new_item_list.append(copy_to_model(**params))

    copy_to_model.objects.bulk_create(new_item_list)


def get_qs_for_bevmin_wonmin(
    obsmodel,
    measures: tuple[str, ...] = (MEASURE_BEVTOTAAL, MEASURE_WVOORRBAG),
    spatialdimensiontypes: tuple[str, ...] = (SPATIAL_DIMENSION_WIJK, SPATIAL_DIMENSION_GGW),
    temporaldimensiontype: str = TEMPORAL_DIMENSIONTYPE_PEILDATUM,
) -> QuerySet:
    """get queryset of observations with only measures bevtotaal and wvoorrbag (default),
    for spatialdimensiontype wijk and ggw-gebied (default)
    and temporaldimensiontype 'Peildatum' (default)
    """
    queryset = (
        obsmodel.objects.select_related("measure", "spatialdimension", "temporaldimension")
        .filter(
            measure__name__in=measures,
            spatialdimension__type__name__in=spatialdimensiontypes,
            temporaldimension__type__name=temporaldimensiontype,
        )
        .annotate(
            spatialdimensiondate=F("spatialdimension__source_date"),
            spatialdimensioncode=F("spatialdimension__code"),
            temporaldimensionstartdate=F("temporaldimension__startdate"),
            temporaldimensionyear=F("temporaldimension__year"),
            measure_name=F("measure__name"),
        )
        .order_by("measure", "temporaldimension__year", "temporaldimension__startdate")
        .defer("created_at", "updated_at")
        .distinct()
    )
    return queryset


def set_small_regions_to_nan_if_minimum(
    dfmin: pd.DataFrame,
    var_min: str,
    dataframe: pd.DataFrame,
    minimum_value: int = None,
) -> pd.DataFrame:
    """set region value to np.nan if var_min is less than minimum_value :
    remove value observation if sd_minimum_bevtotaal or sd_minimum_wvoorrbag condition is not met
    or if minimum_value is set as param: if value observation is smaller than minimum_value
    """

    join_keys = [
        "temporaldimensionyear",
        "spatialdimensiondate",
        "spatialdimensioncode",
    ]

    if dataframe.empty:
        return dataframe

    required_dataframe_columns = set(join_keys + ["measure_name", "value"])
    missing_dataframe_columns = required_dataframe_columns - set(dataframe.columns)
    if missing_dataframe_columns:
        raise ValueError(
            "set_small_regions_to_nan_if_minimum: dataframe is missing required columns "
            f"{sorted(missing_dataframe_columns)}"
        )

    required_dfmin_columns = set(join_keys + ["measure_name", "value"])
    if not required_dfmin_columns.issubset(dfmin.columns):
        logger.warning(
            "set_small_regions_to_nan_if_minimum: dfmin is missing required columns %s; returning original dataframe",
            sorted(required_dfmin_columns - set(dfmin.columns)),
        )
        return dataframe

    # get the values of bevtotaal or wvoorrbag
    _df_var_min = dfmin.loc[dfmin["measure_name"] == var_min, join_keys + ["value"]]

    if _df_var_min.empty:
        return dataframe

    hulp = dataframe.join(
        _df_var_min.rename(columns={"value": "varc"}).set_index(join_keys),
        on=join_keys,
        how="left",
    ).replace({None: np.nan})

    # 'value' vervangen door onbekend als te klein
    if minimum_value is not None:
        threshold = minimum_value
    else:
        minimum_value_column = f"sd_minimum_{var_min.lower()}"
        if minimum_value_column not in hulp.columns:
            raise ValueError(
                "set_small_regions_to_nan_if_minimum: dataframe is missing threshold column "
                f"'{minimum_value_column}' when minimum_value is None"
            )
        threshold = hulp[minimum_value_column]

    mask_too_small = (hulp["measure_name"] != var_min) & (hulp["varc"] < threshold)
    hulp.loc[mask_too_small, "value"] = np.nan
    return hulp.drop("varc", axis=1)
